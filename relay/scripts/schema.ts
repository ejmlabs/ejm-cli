import { URL } from "node:url";
import { DatabaseSync } from "node:sqlite";
import { readFile, writeFile } from "node:fs/promises";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../src/auth.js";
const options = authOptions({ RELAY_ORIGIN: "https://relay.example.invalid", BETTER_AUTH_SECRET: "schema-only-not-a-deployment-secret-at-least-32-characters", GITHUB_CLIENT_ID: "schema", GITHUB_CLIENT_SECRET: "schema" }, new DatabaseSync(":memory:"));
const migrations = await getMigrations(options);
const sql = `-- Generated by Better Auth 1.7.11. Run npm run schema:auth.\n${await migrations.compileMigrations()}\n`;
const path = new URL("../migrations/0000-auth.sql", import.meta.url);
if (process.argv.includes("--check")) { if ((await readFile(path, "utf8")) !== sql) throw new Error("Better Auth migration is stale"); }
else await writeFile(path, sql);
